import { describe, expect, it } from 'vitest';

import { formatLaravelMappings, parseLaravelExportOutput } from '../laravel-format';

const header = 'Generated by test';

describe('Laravel mappings', () => {
  it('formats an array-shape table', () => {
    const result = formatLaravelMappings(
      {
        sections: {
          schema: {
            ok: true,
            data: {
              tables: {
                users: {
                  columns: [
                    { name: 'id', type: 'bigint unsigned', nullable: false },
                    { name: 'team_id', type: 'bigint', nullable: false, default: 1 },
                  ],
                  indexes: [{ columns: ['id'], primary: true }, { columns: ['team_id'] }, { columns: ['email'], unique: true }, { columns: ['name'] }],
                  foreign_keys: [{ columns: ['team_id'], foreign_table: 'teams', foreign_columns: ['id'] }],
                },
              },
            },
          },
        },
      },
      header,
    );
    expect(result.files['schema.md']).toContain('users: !*id bigint unsigned, !team_id bigint=1 | UQ: email | IDX: name | FK: team_id → teams.id\n');
  });

  it('formats an object-shape table', () => {
    const result = formatLaravelMappings(
      {
        sections: {
          schema: {
            ok: true,
            data: {
              tables: {
                users: {
                  columns: {
                    id: { column: 'id', type: 'bigint', attributes: ['unsigned'] },
                    name: { column: 'name', type: 'varchar', attributes: ['nullable'] },
                  },
                  indexes: { primary: { columns: ['id'], attributes: ['primary'] } },
                  foreign_keys: { team: { local_columns: ['team_id'], foreign_table: 'teams', foreign_columns: ['id'] } },
                },
              },
            },
          },
        },
      },
      header,
    );
    expect(result.files['schema.md']).toContain('users: !*id bigint unsigned, name varchar | FK: team_id → teams.id\n');
  });

  it('formats table errors', () => {
    const result = formatLaravelMappings({ sections: { schema: { ok: true, data: { tables: { users: { error: 'unavailable' } } } } } }, header);
    expect(result.files['schema.md']).toContain('users: (error: unavailable)\n');
  });

  it('formats the complete schema file', () => {
    const result = formatLaravelMappings(
      {
        php: '8.3',
        laravel: '11',
        sections: {
          schema: {
            ok: true,
            data: { driver: 'mysql', connection: 'main', tables: { users: { columns: [{ name: 'id', type: 'bigint', nullable: false }], indexes: [] } } },
          },
        },
      },
      header,
    );
    expect(result.files['schema.md']).toBe(
      `# Database schema\n${header}\nPHP 8.3 · Laravel 11 · mysql (connection main)\nLegend: ! NOT NULL · * primary key · =x default · UQ unique index · IDX index · FK foreign key\n\nusers: !id bigint\n`,
    );
  });

  it('formats model details', () => {
    const result = formatLaravelMappings(
      {
        sections: {
          models: {
            ok: true,
            data: {
              'App\\Models\\User': {
                table: 'users',
                attributes: [
                  { name: 'id', fillable: false, increments: true, cast: 'int' },
                  { name: 'name', fillable: true, hidden: true },
                  { name: 'display', appended: true },
                  { name: 'status', cast: 'App\\Enums\\Status' },
                  { name: 'created_at', cast: 'datetime' },
                ],
                relations: [{ name: 'team', type: 'belongsTo', related: 'App\\Models\\Team' }],
                observers: [{ observer: 'App\\Observers\\UserObserver' }, 'App\\Observers\\UserObserver'],
              },
            },
          },
        },
      },
      header,
    );
    expect(result.files['models.md']).toContain('  fillable: name | hidden: name | appended: display | casts: status→Status | observers: UserObserver\n');
    expect(result.files['models.md']).toContain('  rel: team belongsTo Team\n');
  });

  it('sorts models and uses fillable all', () => {
    const result = formatLaravelMappings(
      {
        sections: {
          models: {
            ok: true,
            data: {
              'App\\Models\\Zed': { attributes: [{ name: 'z', fillable: true }] },
              'App\\Models\\Alpha': { attributes: [{ name: 'a', fillable: true }] },
            },
          },
        },
      },
      header,
    );
    expect(result.files['models.md']).toBe(
      `# Eloquent models\n${header}\nColumn types are in schema.md. "fillable: all" means nothing is guarded.\n\nAlpha\n  fillable: all\n\nZed\n  fillable: all\n`,
    );
  });

  it('keeps model error file paths', () => {
    const result = formatLaravelMappings(
      { sections: { models: { ok: true, data: { 'App\\Models\\User': { file: 'app/User.php', error: 'broken' } } } } },
      header,
    );
    expect(result.files['models.md']).toContain('User app/User.php\n  error: broken\n');
  });

  it('formats routes', () => {
    const result = formatLaravelMappings(
      {
        sections: {
          routes: {
            ok: true,
            data: [
              { method: 'GET', uri: 'z', action: 'Vendor\\Controller@x' },
              {
                method: 'DELETE',
                uri: 'account',
                domain: 'api',
                action: 'App\\Http\\Controllers\\AccountController@destroy',
                name: 'account.destroy',
                middleware: ['api', 'App\\Http\\Middleware\\Authenticate:sanctum'],
              },
              { method: 'GET', uri: 'account', action: 'Closure', path: 'routes/web.php' },
            ],
          },
        },
      },
      header,
    );
    expect(result.files['routes.md']).toBe(
      `# Routes\n${header}\nRoutes defined by vendor packages are left out. Middleware is shown by class name.\n\nGET  account  → Closure (routes/web.php)\nDELETE  api/account  → AccountController@destroy  (account.destroy)  [api, Authenticate:sanctum]\n`,
    );
  });

  it('reports section failures while producing other files', () => {
    const result = formatLaravelMappings({ sections: { schema: { ok: false, error: 'schema failed' }, routes: { ok: true, data: [] } } }, header);
    expect(result.failures['schema.md']).toBe('schema failed');
    expect(result.failures['models.md']).toBe('Section missing from the export');
    expect(result.files['routes.md']).toBe(`# Routes\n${header}\nRoutes defined by vendor packages are left out. Middleware is shown by class name.\n\n`);
  });

  it('reports boot and unexpected output errors', () => {
    expect(formatLaravelMappings({ error: 'cannot boot' }, header)).toEqual({ bootError: 'cannot boot', files: {}, failures: {} });
    expect(formatLaravelMappings(null, header)).toEqual({ bootError: 'Unexpected output from the Laravel export', files: {}, failures: {} });
  });

  it('parses leading junk and reports invalid JSON', () => {
    expect(parseLaravelExportOutput('junk {"ok":true}')).toEqual({ ok: true });
    expect(() => parseLaravelExportOutput('not json')).toThrow('not json');
  });
});
